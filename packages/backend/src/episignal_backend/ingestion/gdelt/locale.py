def _key(value: str) -> str:
    return " ".join(value.split()).casefold()


def language_code(name: str) -> str | None:
    return LANGUAGE_CODES.get(_key(name))


def country_code(name: str) -> str | None:
    return COUNTRY_CODES.get(_key(name))
